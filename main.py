import json
from openai import OpenAI

client = OpenAI(api_key="YOUR_OPENAI_API_KEY")

def verify_contest_openai(text, station_name):
    prompt = f"""
    Είσαι ένας βοηθός που αναλύει απομαγνητοφωνημένο κείμενο από το ραδιόφωνο ({station_name}).
    Εξέτασε αν το παρακάτω κείμενο ανακοινώνει ένα ΤΩΡΙΝΟ/ΕΝ ΕΝΕΡΓΕΙΑ διαγωνισμό στον οποίο οι ακροατές μπορούν να συμμετάσχουν ΤΩΡΑ.

    Κείμενο: "{text}"

    Απάντησε ΑΠΟΚΛΕΙΣΤΙΚΑ σε μορφή JSON με την εξής δομή:
    {{
        "is_active_contest": true/false,
        "action_type": "SMS" / "VIBER" / "PHONE" / "FORM" / "UNKNOWN",
        "instructions": "Σύντομη περιγραφή των οδηγιών (π.χ. Στείλτε ΔΩΡΟ στο 19XXX)",
        "confidence": 0.0 έως 1.0
    }}
    """
    
    try:
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            response_format={"type": "json_object"},
            messages=[{"role": "user", "content": prompt}],
            temperature=0.0
        )
        return json.loads(response.choices[0].message.content)
    except Exception as e:
        print(f"Σφάλμα στο LLM Verification: {e}")
        return {"is_active_contest": False}
